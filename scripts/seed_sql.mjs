import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const wines = JSON.parse(await readFile(join(root, 'api/data/wines.sample.json'), 'utf8'));

// Keep in sync with api/src/wineId.ts.
const slug = (s) =>
  s.normalize('NFD').replace(/[\u0300-\u036f]/g, '').toLowerCase()
    .replace(/[^a-z0-9 ]/g, '').trim().replace(/\s+/g, '-');
const wineId = (producer, name, vintage) => {
  const p = slug(producer);
  let n = slug(name);
  if (p && n.startsWith(p + '-')) n = n.slice(p.length + 1);
  return `${p}-${n}-${vintage ?? 'nv'}`;
};

const PRODUCERS = ['Casillero del Diablo', 'L.A. Cetto', 'Yellow Tail', 'Santa Helena', 'Monte Xanic', 'Freixenet'];
const esc = (v) => (v == null ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`);
const num = (v) => (v == null ? 'NULL' : String(v));

const rows = wines.map((w) => {
  const producer = PRODUCERS.find((p) => w.name.startsWith(p + ' '));
  if (!producer) throw new Error(`no producer for ${w.name}`);
  const name = w.name.slice(producer.length + 1);
  const id = wineId(producer, name, w.vintage);
  return `INSERT INTO wines (id, producer, name, vintage, region, country, grapes, abv, color, acidity, sweetness, tannin, body, source) VALUES ('${id}', ${esc(producer)}, ${esc(name)}, ${num(w.vintage)}, ${esc(w.region)}, ${esc(w.country)}, ${esc(JSON.stringify([w.grape]))}, ${num(w.alcohol)}, '${w.color}', ${w.acidity}, ${w.sweetness}, ${w.tannin}, ${w.body}, 'seed');`;
});

const sql = `-- Generated by scripts/seed_sql.mjs from api/data/wines.sample.json. Do not edit.\n${rows.join('\n')}\n`;
await mkdir(join(root, 'api/migrations'), { recursive: true });
await writeFile(join(root, 'api/migrations/0002_seed_wines.sql'), sql);
console.log(`wrote api/migrations/0002_seed_wines.sql (${rows.length} wines)`);
